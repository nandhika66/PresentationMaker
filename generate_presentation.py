# STEP 4 - Main program.
# Asks what presentation you want, retrieves the most relevant slides
# with hybrid search, asks Gemini to write the content and saves a new PPTX.

import json
import re

from pptx import Presentation
from pptx.util import Inches, Pt

from config import OUTPUT_DIR
from generate_content import generate_slide_content
from hybrid_search import hybrid_search, slides

# Minimum number of source slides sent to Gemini
MIN_SOURCE_SLIDES = 5


def retrieve_slides(query, top_k=MIN_SOURCE_SLIDES):
    retrieved = []

    for index, score in hybrid_search(query, top_k=top_k):
        record = dict(slides[index])
        record["retrieval_score"] = float(score)
        retrieved.append(record)

    return retrieved


def safe_filename(text):
    name = re.sub(r"[^A-Za-z0-9]+", "_", text).strip("_")
    return (name or "presentation")[:60]


def create_powerpoint(content, output_path):
    presentation = Presentation()

    # Widescreen 16:9
    presentation.slide_width = Inches(13.333)
    presentation.slide_height = Inches(7.5)

    # The default template is 4:3, so stretch placeholders to 16:9 width
    def fit(shape, top, height):
        shape.left = Inches(0.7)
        shape.width = Inches(11.9)
        shape.top = Inches(top)
        shape.height = Inches(height)

    # Title slide
    title_slide = presentation.slides.add_slide(presentation.slide_layouts[0])
    title_slide.shapes.title.text = content.get("presentation_title", "Presentation")
    fit(title_slide.shapes.title, 2.2, 1.6)
    if len(title_slide.placeholders) > 1:
        title_slide.placeholders[1].text = "Generated by PresentationMaker"
        fit(title_slide.placeholders[1], 4.0, 1.0)

    # Content slides
    for slide_data in content["slides"]:
        slide = presentation.slides.add_slide(presentation.slide_layouts[1])

        title = slide.shapes.title
        title.text = slide_data["title"]
        title.text_frame.paragraphs[0].font.size = Pt(30)
        fit(title, 0.4, 1.1)

        body_shape = slide.placeholders[1]
        fit(body_shape, 1.6, 5.2)

        body = body_shape.text_frame
        body.clear()

        for i, point in enumerate(slide_data["key_points"]):
            paragraph = body.paragraphs[0] if i == 0 else body.add_paragraph()
            paragraph.text = point
            paragraph.level = 0
            paragraph.font.size = Pt(20)

        # Put the sources in the speaker notes
        sources = slide_data.get("source_slides", [])
        if sources:
            slide.notes_slide.notes_text_frame.text = "Sources:\n" + "\n".join(
                f"- {s.get('source_file', '')}, slide {s.get('slide_number', '')}"
                for s in sources
            )

    presentation.save(output_path)


def main():
    print("\n=== PresentationMaker ===")

    user_request = input("What presentation would you like to create? ").strip()
    if not user_request:
        print("Please enter a presentation request.")
        return

    try:
        slide_count = int(input("How many slides do you need? ").strip())
    except ValueError:
        print("Please enter a valid whole number.")
        return

    if not 1 <= slide_count <= 20:
        print("For this prototype, choose between 1 and 20 slides.")
        return

    print("\nSearching your knowledge base...")
    retrieved = retrieve_slides(user_request, top_k=max(MIN_SOURCE_SLIDES, slide_count))

    if not retrieved:
        print("No relevant slides were found.")
        return

    print(f"Retrieved {len(retrieved)} source slides:")
    for slide in retrieved:
        print(f"  - {slide['source_file']} | slide {slide['slide_number']} | {slide['slide_title'][:60]}")

    retrieval_path = OUTPUT_DIR / "last_retrieval.json"
    with open(retrieval_path, "w", encoding="utf-8") as file:
        json.dump(retrieved, file, indent=2, ensure_ascii=False)

    print("\nGenerating presentation content with Gemini...")
    content = generate_slide_content(
        user_request=user_request,
        retrieved_slides=retrieved,
        slide_count=slide_count,
    )

    content_path = OUTPUT_DIR / "generated_content.json"
    with open(content_path, "w", encoding="utf-8") as file:
        json.dump(content, file, indent=2, ensure_ascii=False)

    output_path = OUTPUT_DIR / f"{safe_filename(content.get('presentation_title', user_request))}.pptx"
    create_powerpoint(content, output_path)

    print("\nPresentation created successfully!")
    print(f"PowerPoint:         {output_path}")
    print(f"Generated content:  {content_path}")
    print(f"Retrieved evidence: {retrieval_path}")


if __name__ == "__main__":
    main()
